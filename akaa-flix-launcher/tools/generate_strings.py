#!/usr/bin/env python3
"""Writes launcher-core/src/main/res/values{,-ar}/strings.xml from tools/strings_source.py."""
import os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from strings_source import S
BASE = os.path.join(os.path.dirname(__file__), '..', 'launcher-core', 'src', 'main', 'res')

def esc(t):
    t = t.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    t = t.replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"').replace('\n', '\\n')
    if t.startswith('@') or t.startswith('?'):
        t = '\\' + t
    return t

def write(folder, idx):
    os.makedirs(os.path.join(BASE, folder), exist_ok=True)
    out = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by tools/generate_strings.py – edit tools/strings_source.py -->', '<resources>']
    for k, v in S.items():
        text = v[idx]
        formatted = re.search(r'%\d\$', text) is not None
        attr = '' if formatted or '%' not in text else ' formatted="false"'
        if k == 'app_name' or k.startswith('brand_'):
            attr += ' translatable="false"' if idx == 0 else ''
        out.append(f'    <string name="{k}"{attr}>{esc(text)}</string>')
    out.append('</resources>')
    with open(os.path.join(BASE, folder, 'strings.xml'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')

write('values', 0)
write('values-ar', 1)
# translatable=false strings must not appear in values-ar
p = os.path.join(BASE, 'values-ar', 'strings.xml')
lines = [l for l in open(p, encoding='utf-8') if not re.search(r'name="(app_name|brand_line1|brand_line2)"', l)]
open(p, 'w', encoding='utf-8').writelines(lines)
print(f'{len(S)} strings written')
