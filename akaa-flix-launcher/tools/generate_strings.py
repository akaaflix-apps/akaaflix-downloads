#!/usr/bin/env python3
"""Writes launcher-core/src/main/res/values{,-ar,-fr}/strings.xml.

Sources: tools/strings_source.py (English + Arabic) and tools/strings_fr.py (French, same keys).
French typography (non-breaking space before : ; ! ? and inside « ») is applied here.
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from strings_source import S
from strings_fr import FR

BASE = os.path.join(os.path.dirname(__file__), '..', 'launcher-core', 'src', 'main', 'res')
NOT_TRANSLATABLE = {'app_name', 'brand_line1', 'brand_line2', 'about_website_text', 'about_website_url'}
NBSP = '\u00a0'

missing = [k for k in S if k not in FR]
extra = [k for k in FR if k not in S]
if missing or extra:
    raise SystemExit(f'strings_fr.py out of sync – missing: {missing} extra: {extra}')
for k, (en, _ar) in S.items():
    ph = lambda t: sorted(re.findall(r'%\d\$[sd]', t))
    if ph(en) != ph(FR[k]) or ph(en) != ph(S[k][1]):
        raise SystemExit(f'placeholder mismatch in {k}')


def esc(t):
    t = t.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    t = t.replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"').replace('\n', '\\n')
    if t.startswith('@') or t.startswith('?'):
        t = '\\' + t
    return t


def french(t):
    for p in (':', ';', '?', '!'):
        t = t.replace(' ' + p, NBSP + p)
    return t.replace('« ', '«' + NBSP).replace(' »', NBSP + '»')


def write(folder, text_of, base):
    os.makedirs(os.path.join(BASE, folder), exist_ok=True)
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by tools/generate_strings.py – edit tools/strings_source.py / strings_fr.py -->', '<resources>']
    for k in S:
        if not base and k in NOT_TRANSLATABLE:
            continue
        text = text_of(k)
        formatted = re.search(r'%\d\$', text) is not None
        attr = '' if formatted or '%' not in text else ' formatted="false"'
        if base and k in NOT_TRANSLATABLE:
            attr += ' translatable="false"'
        out.append(f'    <string name="{k}"{attr}>{esc(text)}</string>')
    out.append('</resources>')
    with open(os.path.join(BASE, folder, 'strings.xml'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')


write('values', lambda k: S[k][0], True)
write('values-ar', lambda k: S[k][1], False)
write('values-fr', lambda k: french(FR[k]), False)
print(f'{len(S)} strings written (en, ar, fr)')
