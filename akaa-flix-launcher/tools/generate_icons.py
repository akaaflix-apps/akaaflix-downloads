def gear(cx=12, cy=12, r_out=9.2, r_in=7.0, teeth=8):
    pts = []
    for i in range(teeth):
        a0 = 2 * math.pi * i / teeth
        w = math.pi / teeth
        for a, r in ((a0 - w * 0.55, r_in), (a0 - w * 0.32, r_out), (a0 + w * 0.32, r_out), (a0 + w * 0.55, r_in)):
            pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    d = 'M' + ' L'.join(f'{x:.2f},{y:.2f}' for x, y in pts) + 'z'
    return d

