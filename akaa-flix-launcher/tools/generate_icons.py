MIRROR = {'ic_back', 'ic_chevron_left', 'ic_chevron_right'}

def write(name, paths, default_color=W):
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- Generated by tools/generate_icons.py. Do not edit by hand. -->',
             '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             '    android:width="24dp"', '    android:height="24dp"', '    android:viewportWidth="24"', '    android:viewportHeight="24"' + ('>' if name not in MIRROR else '')]
    if name in MIRROR:
        lines[-1] += ''
        lines.append('    android:autoMirrored="true">')
    for p in paths:
        d, mode = p[0], p[1]
        color = p[2] if len(p) > 2 else default_color
        width = p[3] if len(p) > 3 else 1.8
        if mode == S:
            lines.append(f'    <path android:pathData="{d}" android:strokeColor="{color}" android:strokeWidth="{width}" '
                         f'android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000" />')
        else:
            lines.append(f'    <path android:pathData="{d}" android:fillColor="{color}" />')
    lines.append('</vector>')
    with open(os.path.join(OUT, name + '.xml'), 'w') as f:
        f.write('\n'.join(lines) + '\n')

