#!/usr/bin/env python3
"""Generates app/src/main/res/values/strings.xml (English) and values-ar/strings.xml (Arabic)."""
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).parent))
from strings_source import S  # noqa: E402

ROOT = Path(__file__).resolve().parents[1] / "app" / "src" / "main" / "res"


def esc(text: str) -> str:
    t = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    t = t.replace("'", "\\'").replace('"', '\\"')
    return t


def write(folder: str, idx: int) -> None:
    out = ROOT / folder
    out.mkdir(parents=True, exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/generate_strings.py — edit tools/strings_source.py instead. -->", "<resources>"]
    for key, pair in S.items():
        attrs = ' translatable="false"' if key == "app_name" and idx == 0 else ""
        if key == "app_name" and idx == 1:
            continue
        val = esc(pair[idx])
        if "%" in val and "%1$" not in val and "%2$" not in val:
            val = val.replace("%", "%%")
        lines.append(f'    <string name="{key}"{attrs}>{val}</string>')
    lines.append("</resources>")
    (out / "strings.xml").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    write("values", 0)
    write("values-ar", 1)
    print(f"Wrote {len(S)} strings")
